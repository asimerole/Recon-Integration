using System.IO;
using Recon.Core.Domain.Models;

namespace Recon.Core.Application.Services;

/// <summary>Builds RECON/REXPR pairs from an object's files (full archive scan).</summary>
internal static class FilePairing
{
    public static readonly TimeSpan MaxPairGap = TimeSpan.FromDays(2);

    /// <summary>
    /// File numbers repeat every 1000 events, so RECON353.300 can exist several times in an object.
    /// Within one (recon, number): a RECON pairs with the REXPR in the same folder; otherwise with the REXPR
    /// closest in time but not further than <paramref name="maxGap"/> (month boundary: 31.10 23:59 / 01.11 00:00).
    /// The old key "recon.number.yyyyMM of mtime" split pairs at month boundaries and always split a REXPR
    /// generated by OMP_C later (its mtime is the generation moment) — two records per event on every rebuild.
    /// Expects Timestamp = file mtime (as BaseFileFactory sets it).
    /// </summary>
    public static List<FilePair> Pair(IEnumerable<BaseFile> files, TimeSpan? maxGap = null)
    {
        var gap = maxGap ?? MaxPairGap;
        var pairs = new List<FilePair>();

        foreach (var group in files.GroupBy(f => (f.ReconNumber, f.FileNum)))
        {
            foreach (var other in group.OfType<ReconFile>())
                pairs.Add(new FilePair { Other = other });

            var expresses = group.OfType<ExpressFile>().ToList();
            foreach (var data in group.OfType<DataFile>().OrderBy(d => d.Timestamp))
            {
                string? dir = Path.GetDirectoryName(data.FullPath);
                var match = expresses.FirstOrDefault(e =>
                                string.Equals(Path.GetDirectoryName(e.FullPath), dir, StringComparison.OrdinalIgnoreCase))
                            ?? expresses
                                .Where(e => (e.Timestamp - data.Timestamp).Duration() <= gap)
                                .MinBy(e => (e.Timestamp - data.Timestamp).Duration());

                if (match != null) expresses.Remove(match);
                pairs.Add(new FilePair { Data = data, Express = match });
            }

            foreach (var express in expresses)
                pairs.Add(new FilePair { Express = express });
        }

        return pairs;
    }

    /// <summary>"2026_11" month folder of an event: files of a pair are sorted together by the RECON's time.</summary>
    public static string MonthFolder(DateTime time) => $"{time.Year:D4}_{time.Month:D2}";
}
